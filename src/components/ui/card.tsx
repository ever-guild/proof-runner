import * as React from "react"
import { cn } from "../../lib/utils"

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-2xl border border-white/10 bg-black/40 shadow-glass backdrop-blur-2xl text-slate-50 relative overflow-hidden",
      "before:absolute before:inset-0 before:-z-10 before:rounded-2xl before:shadow-inner-light before:pointer-events-none",
      className
    )}
    {...props}
  />
))
Card.displayName = "Card"

